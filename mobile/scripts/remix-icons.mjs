// Generates src/components/remix-icons.ts from the web app's @remixicon/react, so the app draws
// the same icons as the web app. Run from mobile/: node scripts/remix-icons.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(new URL('../../package.json', import.meta.url));
const icons = require('@remixicon/react');
const NAMES = [
  'RiArrowLeftLine', 'RiArrowRightLine', 'RiArrowLeftSLine', 'RiArrowRightSLine', 'RiArrowDownSLine',
  'RiCheckLine', 'RiCheckboxCircleFill', 'RiCheckboxCircleLine', 'RiCheckboxBlankCircleLine', 'RiCheckDoubleLine',
  'RiGitBranchLine', 'RiChat3Line', 'RiFileTextLine', 'RiFileList3Line', 'RiSparklingLine', 'RiShareLine',
  'RiLinksLine', 'RiFileCopyLine', 'RiExternalLinkLine', 'RiErrorWarningLine', 'RiInformationLine', 'RiTimeLine',
  'RiUserLine', 'RiAddLine', 'RiDeleteBinLine', 'RiReplyLine', 'RiExpandUpDownLine', 'RiNotification3Line',
  'RiTeamLine', 'RiMoonLine', 'RiServerLine', 'RiLogoutBoxRLine', 'RiTextWrap', 'RiEyeLine', 'RiEdit2Line',
  'RiMore2Fill', 'RiMoreFill', 'RiCloseLine', 'RiSearchLine', 'RiFilter3Line', 'RiGitPullRequestLine',
  'RiBarChart2Line', 'RiSettings3Line', 'RiHistoryLine', 'RiDownloadLine', 'RiRefreshLine', 'RiGlobalLine',
];

function paths(el, out = []) {
  if (!el || typeof el !== 'object') return out;
  if (el.type === 'path' && el.props?.d) out.push(el.props.d);
  const kids = el.props?.children;
  for (const k of Array.isArray(kids) ? kids : [kids]) paths(k, out);
  return out;
}

const out = {};
for (const name of NAMES) {
  const Comp = icons[name];
  if (!Comp) throw new Error(`Unknown icon ${name}`);
  const render = Comp.render ?? Comp;
  const el = render({ size: 24 }, null);
  const d = paths(el);
  if (d.length === 0) throw new Error(`No paths for ${name}`);
  out[name.replace(/^Ri/, '')] = d.join(' ');
}
const body = `/* Generated by scripts/remix-icons.mjs from @remixicon/react (Apache-2.0). Do not edit. */\nexport const REMIX = ${JSON.stringify(out, null, 2)} as const;\n\nexport type RemixName = keyof typeof REMIX;\n`;
writeFileSync(new URL('../src/components/remix-icons.ts', import.meta.url), body);
console.log(`wrote ${Object.keys(out).length} icons`);
